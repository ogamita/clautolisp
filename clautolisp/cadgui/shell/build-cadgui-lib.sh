#!/bin/bash
# Build clautolisp-cadgui.a: a monolithic static library of clautolisp/cadgui +
# its closure, for the C++ cadgui shell to link in (see build-cadgui-lib.lisp).
# Builds COLD (cache cleared) so make-build's ASDF planning does not overflow.
#
# ECL's monolithic bundle gets a RANDOMISED init symbol (init_lib__<tag>),
# regenerated each build, so we cannot hardcode it. After the build we extract
# it with nm and generate cadgui-lib-init.h, which the shell #includes. Run
# build.sh with CADGUI_USE_LIB=1 to compile+link the frozen-engine shell.
set -u
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"             # .../clautolisp (holds clautolisp.asd)
export CADGUI_CLAUTOLISP_DIR="$root"
lib="$here/clautolisp--cadgui--all-systems.a"
hdr="$here/cadgui-lib-init.h"

echo "build-cadgui-lib: clearing the ecl-* asdf cache for a clean cold build ..."
rm -rf "$HOME/.cache/common-lisp/ecl-"* 2>/dev/null || true
{ ulimit -s 262144 2>/dev/null || ulimit -s 131072 2>/dev/null || ulimit -s 65536 2>/dev/null || true; }
cd "$root" || exit 3
ecl --norc --load "$here/build-cadgui-lib.lisp" </dev/null
rc=$?
if [ "$rc" -ne 0 ]; then echo "build-cadgui-lib: ecl build failed ($rc)"; exit "$rc"; fi
if [ ! -f "$lib" ]; then echo "build-cadgui-lib: $lib not produced"; exit 2; fi

# Extract the monolithic init symbol and generate the header the shell includes.
init="$(nm --defined-only "$lib" 2>/dev/null | grep -oE 'init_lib__[A-Za-z0-9_]+' | head -1)"
if [ -z "$init" ]; then echo "build-cadgui-lib: could not find init_lib_ symbol in $lib"; exit 3; fi
{
  echo "/* generated by build-cadgui-lib.sh -- do not edit. */"
  echo "#ifndef CADGUI_LIB_INIT_H"
  echo "#define CADGUI_LIB_INIT_H"
  echo "extern \"C\" void ${init}(cl_object);"
  echo "#define CADGUI_LIB_INIT ${init}"
  echo "#endif"
} > "$hdr"
echo "build-cadgui-lib: $lib"
echo "build-cadgui-lib: init symbol ${init} -> $(basename "$hdr")"
echo "build-cadgui-lib: now build the frozen shell with:  CADGUI_USE_LIB=1 bash build.sh"
