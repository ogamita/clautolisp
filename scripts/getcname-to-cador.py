#!/usr/bin/env python3
"""Convert getcname probe reports into the per-product table clautolisp's
GETCNAME answers from (cadtui-locale-probe-getcname).

Unlike scripts/cadtui-getcname-to-sexp.py (cadtui's merged :command
dictionary), this keeps what EACH product's getcname answers, including the
commands whose local name is the international one (IDENTITY: ZOOM, ARC ...):
the products know different command sets (a French AutoCAD 2022 answers nil
for _RECTANG, _MTEXT, _PROPERTIES ...; BricsCAD V25 for _BLEND, _XBIND ...),
and getcname answers "ZOOM" for "_ZOOM" where the dictionary has no entry.

    scripts/getcname-to-cador.py fr_FR autocad=dist/getcname/autocad-Windows.txt \\
        bricscad=dist/getcname/bricscad-Windows.txt \\
        -o clautolisp/cador/data/getcname/fr_FR.sexp

Each report is a run-getcname-probe.{sh,ps1} output; a VALUE line is kept
only when its round trip closes (GETCNAME-RT gives the input back).
"""
import argparse
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location(
    'cadtui_getcname_to_sexp', os.path.join(HERE, 'cadtui-getcname-to-sexp.py'))
_conv = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_conv)


def table(path):
    """(engine fields, [(international, local)]) of one report."""
    engine, forward, back = [], [], {}
    for line in _conv._decode(path).replace('\r', '').split('\n'):
        parts = line.split('\t')
        if parts[0] == 'GETCNAME-ENGINE':
            engine = [p.strip() for p in parts[1:] if p.strip()]
        elif parts[0] == 'GETCNAME' and len(parts) >= 4 and parts[2] in ('VALUE', 'IDENTITY'):
            forward.append((parts[1], parts[2], parts[3]))
        elif parts[0] == 'GETCNAME-RT' and len(parts) >= 4 and parts[2] == 'VALUE':
            back[parts[1]] = parts[3]
    pairs = []
    for intl, status, local in forward:
        if status == 'IDENTITY' or back.get(local) == intl:
            pairs.append((intl.upper(), local.upper()))
    return engine, sorted(set(pairs))


def lisp_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('locale')
    ap.add_argument('reports', nargs='+', help='PRODUCT=REPORT (autocad / bricscad)')
    ap.add_argument('-o', '--output', required=True)
    args = ap.parse_args()
    out = [';;;; -*- mode:lisp; coding:utf-8 -*-',
           ';;;; GENERATED by scripts/getcname-to-cador.py -- do not edit by hand.',
           ';;;; What each product\'s GETCNAME answers under locale %s, measured by the' % args.locale,
           ';;;; getcname probe: (PRODUCT (INTERNATIONAL . LOCAL) ...), the round trip',
           ';;;; closing for every translated name; an IDENTITY command has LOCAL equal',
           ';;;; to INTERNATIONAL without its underscore.']
    body = []
    for spec in args.reports:
        product, path = spec.split('=', 1)
        engine, pairs = table(path)
        out.append(';;;;   %s: %s  [%s] -- %d commands'
                   % (product, os.path.basename(path), '  '.join(engine), len(pairs)))
        body.append(' (:%s' % product.upper())
        body.extend('  (%s . %s)' % (lisp_string(i), lisp_string(l)) for i, l in pairs)
        body[-1] += ')'
    out.append('(')
    out.extend(body)
    out.append(')')
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
