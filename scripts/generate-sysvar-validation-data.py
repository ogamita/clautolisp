#!/usr/bin/env python3
"""Generate clautolisp/cador/source/sysvar-validation-data.lisp -- the data
SETVAR validates against (setvar-validation-as-measured):

  *sysvar-integer-ranges*   ("NAME" LO HI) for the integer / short system
                            variables with a documented range (LO / HI NIL
                            when unbounded on that side), from
                            autolisp-spec/documentation/system-variables-inventory.sexp,
                            plus the ranges measured where the inventory has
                            none (MEASURED_RANGES below);
  *sysvar-range-overrides*  ("NAME" PRODUCT LO HI): a product whose
                            measured range is wider than the documented one
                            -- a boundary value it ACCEPTED in the sunset
                            campaign's B5 capture (probe-sysvar-flags.lsp);
  *sysvar-2d-point-names*   the point variables the inventory types :point
                            (2D), as opposed to :point3d.

Usage: python3 scripts/generate-sysvar-validation-data.py
Re-run after the inventory or a B5 capture changes; never edit the output.
"""
import re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INVENTORY = os.path.join(ROOT, 'autolisp-spec/documentation/system-variables-inventory.sexp')
OUT = os.path.join(ROOT, 'clautolisp/cador/source/sysvar-validation-data.lisp')
# The B5 captures (2026-11-16): product -> results.sexp
B5 = {
    'autocad': 'probe-results/autocad/ms-windows/20261116T180525Z/results.sexp',
    'bricscad': 'probe-results/bricscad/ms-windows/20261116T181223Z/results.sexp',
}
# Measured where the inventory documents no range (B4, probe-setvar-edges.lsp,
# 2026-10-28): both products refuse (setvar "CMDECHO" 2).
MEASURED_RANGES = {'CMDECHO': (0, 1)}


def inventory():
    text = open(INVENTORY, encoding='utf-8').read()
    for chunk in re.split(r'\n\(\s*\n', text):
        m = re.search(r':name "([^"]+)"', chunk)
        if not m:
            continue
        def get(key):
            mm = re.search(r':%s (\S.*)' % key, chunk)
            return mm.group(1).strip() if mm else None
        yield m.group(1), get('type'), get('range')


def parse_range(text):
    m = re.match(r'\((\S+) (\S+)\)', text or '')
    if not m:
        return None
    lo, hi = (None if x == 'NIL' else int(x) for x in m.groups())
    return (lo, hi) if (lo is not None or hi is not None) else None


def b5_accepted(path):
    """{(NAME, VALUE)} the product stored (no error) in B5's range cases."""
    accepted = set()
    rec = re.compile(r'\(CASE \. "\(cad-probe--b5sv \\"([A-Z0-9_]+)\\" (-?\d+)\)"\) '
                     r'\(STATUS \. "ok"\) \(VALUE \. "(.*)"\)\)$')
    for line in open(os.path.join(ROOT, path), encoding='utf-8', errors='replace'):
        m = rec.search(line.rstrip())
        if m and not m.group(3).startswith('((ERROR') and not m.group(3).startswith('((error'):
            accepted.add((m.group(1), int(m.group(2))))
    return accepted


def main():
    ranges, points2d = {}, []
    for name, typ, rng in inventory():
        if typ in (':integer', ':short'):
            r = parse_range(rng)
            if r:
                ranges[name] = r
        elif typ == ':point':
            points2d.append(name)
    for name, r in MEASURED_RANGES.items():
        ranges.setdefault(name, r)
    overrides = []
    for product, path in B5.items():
        accepted = b5_accepted(path)
        for name, (lo, hi) in sorted(ranges.items()):
            new_lo = lo - 1 if lo is not None and (name, lo - 1) in accepted else lo
            new_hi = hi + 1 if hi is not None and (name, hi + 1) in accepted else hi
            if (new_lo, new_hi) != (lo, hi):
                overrides.append((name, product, new_lo, new_hi))

    def lisp(x):
        return 'NIL' if x is None else str(x)

    with open(OUT, 'w', encoding='utf-8') as out:
        out.write(''';;;; -*- Mode: Lisp; coding: utf-8 -*-
;;;; THIS FILE IS GENERATED by scripts/generate-sysvar-validation-data.py.
;;;; Do not edit by hand: re-run the script.
;;;;
;;;; The data SETVAR validates against (setvar-validation-as-measured): the
;;;; integer ranges (documented, or measured where undocumented), the ranges a
;;;; product measurably widens (sunset campaign B5, 2026-11-16), and the 2D
;;;; point variables.

(in-package #:clautolisp.cador)

(defparameter *sysvar-integer-ranges*
  '(''')
        out.write('\n    '.join('("%s" %s %s)' % (n, lisp(lo), lisp(hi))
                                for n, (lo, hi) in sorted(ranges.items())))
        out.write('''))

(defparameter *sysvar-range-overrides*
  '(''')
        out.write('\n    '.join('("%s" :%s %s %s)' % (n, p, lisp(lo), lisp(hi))
                                for n, p, lo, hi in overrides))
        out.write('''))

(defparameter *sysvar-2d-point-names*
  '(''')
        out.write('\n    '.join('"%s"' % n for n in sorted(points2d)))
        out.write('))\n')
    print('ranges %d, overrides %d, 2D points %d -> %s'
          % (len(ranges), len(overrides), len(points2d), os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    main()
